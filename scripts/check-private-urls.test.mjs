/**
 * Tests for `scripts/check-private-urls.mjs`.
 *
 * Usage:
 *   pnpm exec vitest run scripts/check-private-urls.test.mjs
 */

import { describe, expect, it } from "vitest";

import {
  findPrivateUrls,
  findProblems,
  formatProblem,
} from "./check-private-urls.mjs";

/** @param {string} text */
const urls = (text) => findPrivateUrls(text).map(({ url }) => url);

describe(findPrivateUrls, () => {
  it("finds a session URL in a commit trailer", () => {
    const text = `feat(web): add new feature

Co-Authored-By: Someone <someone@example.com>
Claude-Session: https://claude.ai/code/session_01AbCdEf
`;

    expect(findPrivateUrls(text)).toStrictEqual([
      {
        line: 4,
        name: "Claude のセッション・アーティファクト・会話・プロジェクト",
        url: "https://claude.ai/code/session_01AbCdEf",
      },
    ]);
  });

  it("stops the URL before Markdown punctuation", () => {
    expect(
      urls("_Generated by [Claude Code](https://claude.ai/code/session_01Ab)_")
    ).toStrictEqual(["https://claude.ai/code/session_01Ab"]);
    expect(urls("<https://claude.ai/chat/0123-abcd>")).toStrictEqual([
      "https://claude.ai/chat/0123-abcd",
    ]);
  });

  it("finds artifacts, chats and projects", () => {
    expect(
      urls(`https://claude.ai/code/artifact/0123
https://claude.ai/artifact/abcd
https://claude.ai/chat/0123
http://www.claude.ai/project/abcd`)
    ).toStrictEqual([
      "https://claude.ai/code/artifact/0123",
      "https://claude.ai/artifact/abcd",
      "https://claude.ai/chat/0123",
      "http://www.claude.ai/project/abcd",
    ]);
  });

  it("finds every URL on a line", () => {
    expect(
      urls("https://claude.ai/chat/a and https://claude.ai/chat/b")
    ).toStrictEqual(["https://claude.ai/chat/a", "https://claude.ai/chat/b"]);
  });

  it("accepts URLs that anyone can open", () => {
    expect(
      urls(`🤖 Generated with [Claude Code](https://claude.com/claude-code)
https://claude.ai/
https://claude.ai/code
https://code.claude.com/docs/en/claude-code-on-the-web
https://github.com/inabagumi/shinju-date/issues/7329`)
    ).toStrictEqual([]);
  });

  it("accepts text without a scheme", () => {
    expect(urls("`claude.ai/code/session_…` の形の URL")).toStrictEqual([]);
  });
});

describe(findProblems, () => {
  it("labels the URLs with their sources", () => {
    const problems = findProblems([
      { label: "タイトル", text: "fix(web): fix a bug" },
      { label: "本文", text: "Line 1\nhttps://claude.ai/code/session_01Ab" },
      // The body of a pull request is null when it is empty
      { label: "本文", text: /** @type {any} */ (null) },
    ]);

    expect(problems.map(formatProblem)).toStrictEqual([
      "本文 (2 行目): https://claude.ai/code/session_01Ab (Claude のセッション・アーティファクト・会話・プロジェクト)",
    ]);
  });
});
